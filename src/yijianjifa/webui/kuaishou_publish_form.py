def verify_form(raw,form,*,declaration_binding=None):
    return (isinstance(raw,dict) and compact(raw.get('caption'))==compact(form['caption'])
            and raw.get('tags')==form['tags'] and raw.get('time_text','')==form['time_text']
            and raw.get('mode')==form['mode'] and raw.get('upload_complete') is True
            and raw.get('button_count')==1 and raw.get('button_enabled') is True
            and verify_declaration(raw,form,declaration_binding=declaration_binding))


def resolve_declaration(raw,form):
    """Freeze a proved legacy source or the current form's observed statementId."""
    if type(raw) is not dict or type(raw.get('declaration_count')) is not int or raw.get('declaration_count')!=1:
        raise ValueError('kuaishou declaration control ambiguous')
    expected=form['declaration']
    if raw.get('declaration_variant')=='legacy':
        return {'kind':'legacy',**expected}
    if raw.get('declaration_variant')!='account_statement':
        raise ValueError('kuaishou declaration form not verified')
    if expected['choice']=='none':raise ValueError('kuaishou author statement required')
    options=raw.get('declaration_options')
    if (type(options) is not list or not options or len(options)>100
            or any(type(v) is not dict or set(v)!={'id','name'} or type(v['id']) is not int
                   or abs(v['id'])>9007199254740991 or type(v['name']) is not str or not v['name'] or len(v['name'])>120 for v in options)
            or len({v['id'] for v in options})!=len(options)):
        raise ValueError('kuaishou author statement options not verified')
    matches=[v for v in options if v['name']==expected['name']]
    if len(matches)!=1:raise ValueError('kuaishou declaration option not verified')
    return {'kind':'account_statement','choice':expected['choice'],'name':expected['name'],'statement_id':matches[0]['id']}


def verify_declaration(raw,form,*,declaration_binding=None):
    """Read the selected normal DOM label; never read or mutate React state."""
    try:current=resolve_declaration(raw,form)
    except (ValueError,TypeError,KeyError):return False
    if current['kind']=='account_statement' and declaration_binding is None:return False
    if declaration_binding is not None and current!=declaration_binding:return False
    return (raw.get('declaration_label')==current['name'] and type(raw.get('declaration_item_count')) is int
            and raw.get('declaration_item_count')==(0 if current['choice']=='none' else 1))


def verify_submit_declaration(request,form,*,declaration_binding=None):
    """Bind the page-generated final POST to the exact proved source mapping.

    Missing/null/empty objects are only compatible with no declaration. A
    statementId, a stringified object, extra source metadata or an unknown key
    cannot establish this legacy choice, even if the platform returned success.
    """
    if type(request) is not dict:return False
    value=request.get('declareInfo')
    if declaration_binding is not None:
        if (type(declaration_binding) is not dict or declaration_binding.get('choice')!=form['declaration']['choice']
                or declaration_binding.get('name')!=form['declaration']['name']):return False
        if declaration_binding.get('kind')=='account_statement':
            statement_id=declaration_binding.get('statement_id')
            return (set(declaration_binding)=={'kind','choice','name','statement_id'}
                    and declaration_binding['choice']!='none' and type(statement_id) is int and abs(statement_id)<=9007199254740991
                    and type(value) is dict and set(value)=={'statementId'}
                    and type(value['statementId']) is int and value['statementId']==statement_id)
        if declaration_binding!={'kind':'legacy',**form['declaration']}:return False
    source=form['declaration']['source']
    if source is None:return value is None or type(value) is dict and not value
    return type(value) is dict and set(value)=={'source'} and type(value['source']) is int and value['source']==source


def safe_id(value):
    if type(value) is int and 0<value<=9007199254740991:value=str(value)
    return value if type(value) is str and re.fullmatch(r'[A-Za-z0-9_.:-]{1,128}',value) else None


def receipt_reference(data):
    if type(data) is not dict:return {}
    result={}
    for field,target in [('workId','work_id'),('publishId','publish_id')]:
        value=safe_id(data.get(field))
        if value is not None:result[target]=value
    return result


def verified_row(rows, reference, form):
    if not reference:return None
    matches=[]
    for row in rows:
        if type(row) is not dict:continue
        actual=receipt_reference(row)
        if not all(actual.get(k)==v for k,v in reference.items()):continue
        if compact(row.get('title'))!=compact(form['caption']):continue
        if type(row.get('publishStatus')) is not int or type(row.get('publishType')) is not int:continue
        if form['publish_ms'] and row.get('publishType')!=2:continue
        state={1:'platform_accepted',2:'processing',4:'published',10:'reviewing',11:'platform_rejected'}.get(row.get('publishStatus'))
        if state:matches.append({'state':state,'reference':actual})
    return matches[0] if len(matches)==1 else None
