def compact(value):
    return ' '.join(value.split()) if isinstance(value,str) else ''


def validate_form(payload, *, query=False, now=None):
    fields=payload['fields']
    allowed={'title','body','tags','cover','location','declaration','content_declaration_choice'}
    if type(fields) is not dict or set(fields)-allowed:
        raise ValueError('kuaishou fields not verified')
    if fields.get('location') is not None or fields.get('declaration') is not None:
        raise ValueError('kuaishou rich fields not verified')
    declaration=declarations.selection(fields.get('content_declaration_choice','none'))
    cover=fields.get('cover') or {'kind':'first_frame','frame_ms':0}
    if cover.get('kind')!='first_frame' or cover.get('frame_ms',0)!=0:
        raise ValueError('kuaishou custom cover not verified')
    title=fields.get('title','');body=fields.get('body','');tags=fields.get('tags','')
    if any(type(v) is not str for v in (title,body,tags)) or not title.strip():
        raise ValueError('invalid caption')
    names=[s.lstrip('#') for s in tags.split()]
    if len(names)>4 or len(set(names))!=len(names) or any(not s or '#' in s or len(s)>20 for s in names):
        raise ValueError('invalid topics')
    text=title+('\n'+body if body else '')
    caption=text+(' '+' '.join('#'+s for s in names) if names else '')
    if len(caption.encode('utf-16-le'))//2>500:
        raise ValueError('kuaishou caption exceeds 500 characters')
    mode=payload['execution_mode'];when=None;time_text='';publish_ms=0
    if mode not in {'publish_now','software_schedule','platform_schedule'}:
        raise ValueError('execution mode not verified')
    if mode=='platform_schedule':
        when=datetime.fromisoformat(payload['scheduled_at'])
        if when.tzinfo is None or when.second or when.microsecond:
            raise ValueError('schedule requires a timezone and whole minute')
        current=now or datetime.now(timezone.utc)
        if not query and not current+timedelta(hours=2.5)<=when<=current+timedelta(days=13):
            raise ValueError('schedule outside verified window')
        time_text=when.astimezone(timezone(timedelta(hours=8))).strftime('%Y-%m-%d %H:%M')
        publish_ms=int(when.timestamp()*1000)
    return {'text':text,'tags':names,'caption':caption,'time_text':time_text,'publish_ms':publish_ms,
            'mode':'定时发布' if when else '立即发布','declaration':declaration}


