from __future__ import annotations

from typing import Protocol, Any

from yijianjifa.features.accounts.models import CapabilitySnapshot


class PlatformAdapter(Protocol):
    platform_id: str

    def login(self, *args, **kwargs) -> Any: ...
    def identity(self) -> str: ...
    def check_capabilities(self, *, allow_upload_probe: bool = False) -> CapabilitySnapshot: ...
    def prepare_normal(self, request) -> Any: ...
    def submit_normal(self, request) -> Any: ...
    def verify_result(self, evidence) -> Any: ...
